# 2. Function to load and clean a model file on the fly
def load_fixed_module(file_name, module_name):
    file_path = os.path.join(model_folder_path, file_name)
    if not os.path.exists(file_path):
        print(f"Error: {file_name} not found at {file_path}")
        return None

    with open(file_path, 'r', encoding='utf-8') as f:
        raw_content = f.read()

    code_text = ""
    # Try to parse as Jupyter notebook JSON
    try:
        notebook_data = json.loads(raw_content)
        python_code_parts = []
        for cell in notebook_data.get('cells', []):
            if cell.get('cell_type') == 'code':
                # Join source lines, ensuring they are strings, and add a newline
                python_code_parts.append(''.join(cell.get('source', [])))
        code_text = '\n'.join(python_code_parts)
        if not code_text.strip(): # If no code found in JSON, might be empty notebook or malformed
            raise ValueError("No executable code found in Jupyter notebook format.")
        print(f"Detected {file_name} as Jupyter notebook, extracted code.")
    except json.JSONDecodeError:
        # Not a JSON, assume it's a plain Python file
        code_text = raw_content
        print(f"Detected {file_name} as plain Python file.")
    except ValueError as e:
        print(f"Warning: Failed to extract code from {file_name} as Jupyter notebook: {e}. Treating as plain Python.")
        code_text = raw_content

    # Aggressively replace any lowercase javascript booleans with Python ones
    code_text = re.sub(r'\btrue\b', 'True', code_text, flags=re.IGNORECASE)
    code_text = re.sub(r'\bfalse\b', 'False', code_text, flags=re.IGNORECASE)

    # Create module container
    spec = importlib.util.spec_from_file_location(module_name, file_path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = mod

    # Execute the cleaned code
    try:
        exec(code_text, mod.__dict__) # This executes the *string* content
        print(f"Successfully loaded and cleaned {module_name}!")
        return mod
    except Exception as e:
        print(f"Error executing code for {module_name}: {e}")
        return None

