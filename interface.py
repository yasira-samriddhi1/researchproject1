def predict_cytarabine(file):
    if file is None:
        raise gr.Error('Please upload a cell line data file first!')

    time.sleep(1)

    # 1. Run model_1 safely
    model_1_output = None
    if 'model_1' in globals() and hasattr(model_1, 'run'):
        try:
            model_1_output = model_1.run(file)
        except Exception as e:
            print(f"model_1 execution note: {e}")

    # 2. Run model_2 normally
    model_2_output = None
    try:
        if 'model_2' in globals() and hasattr(model_2, 'run'):
            model_2_output = model_2.run(model_1_output, file)
    except Exception as e:
        print(f"model_2 execution error: {e}")

    # 3. Load the saved graphs
    saved_graphs = []

    for i in range(1, 6):
        graph_path = os.path.join(
            GRAPH_FOLDER,
            f"graph_{i}.png"
        )

        if os.path.exists(graph_path):
            saved_graphs.append(graph_path)
        else:
            saved_graphs.append(None)

    # 4. Extract text strings or dataframe descriptions from model_2 output
    extracted_texts = []

    if isinstance(model_2_output, (list, tuple)):
        for item in model_2_output:
            if isinstance(item, str):
                extracted_texts.append(item)
            elif hasattr(item, 'to_string'):
                extracted_texts.append(str(item))

    # 5. Build the exact 10-item tuple required by Gradio
    response_items = []

    for i in range(5):

        if saved_graphs[i] is not None:
            response_items.append(saved_graphs[i])
        else:
            response_items.append(None)

        if i < len(extracted_texts):
            response_items.append(extracted_texts[i])
        else:
            response_items.append(f"Analysis insights for Graph {i+1}.")

    return tuple(response_items)

